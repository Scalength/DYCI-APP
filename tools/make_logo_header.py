#!/usr/bin/env python3
"""Regenerate the embedded DYCI seal used by the app header.

Run from the project root (or anywhere):

    python tools/make_logo_header.py [path/to/logo]

  - input:  assets/dyci-logo.webp by default (any square-ish logo;
            transparent background recommended, e.g. PNG or WebP)
  - output: src/logo_dyci.png  (240x240, palette PNG, alpha preserved)
            src/logo_dyci.h   (the PNG as C bytes, included by main.c)

After running this, rebuild the app (make / make portable). Nothing else
references the logo: it is embedded in the executable, so no extra file
ships with the portable bundle.
"""
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "assets", "dyci-logo.webp")
PNG = os.path.join(ROOT, "src", "logo_dyci.png")
HDR = os.path.join(ROOT, "src", "logo_dyci.h")

im = Image.open(SRC).convert("RGBA")
print("source:", SRC, im.size)

# center-crop to a square, then shrink to the 2x asset size
side = min(im.size)
im = im.crop(((im.width - side) // 2, (im.height - side) // 2,
              (im.width + side) // 2, (im.height + side) // 2))
im = im.resize((240, 240), Image.LANCZOS)

# shrink: 256-color palette PNG (logos use few colors) — alpha preserved
# via the palette. Fall back to full RGBA if the alpha broke.
im.save(PNG, optimize=True)
q = im.quantize(256, method=Image.FASTOCTREE)
q.save(PNG + ".quantized.png", optimize=True)
back = Image.open(PNG + ".quantized.png").convert("RGBA")
aq = back.getchannel("A")
corners_ok = all(aq.getpixel(p) == 0 for p in [(0, 0), (239, 0), (0, 239), (239, 239)])
print("rgba bytes:", os.path.getsize(PNG),
      "| palette bytes:", os.path.getsize(PNG + ".quantized.png"),
      "| corners ok:", corners_ok)
if corners_ok and os.path.getsize(PNG + ".quantized.png") < os.path.getsize(PNG):
    os.replace(PNG + ".quantized.png", PNG)
    print("using palette PNG")
else:
    os.remove(PNG + ".quantized.png")
    print("using RGBA PNG")
print("png bytes:", os.path.getsize(PNG))

# generate the C header with the embedded PNG bytes
data = open(PNG, "rb").read()
lines = [
    "/* logo_dyci.h — the DYCI seal embedded into the executable.",
    " * GENERATED by tools/make_logo_header.py from src/logo_dyci.png",
    " * — do not edit by hand. The PNG keeps the transparent background. */",
    "#ifndef LOGO_DYCI_H",
    "#define LOGO_DYCI_H",
    "",
    "#include <stddef.h>",
    "",
    "static const unsigned char LOGO_DYCI_PNG[] = {",
]
for i in range(0, len(data), 16):
    chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
    lines.append(f"    {chunk},")
lines += [
    "};",
    "",
    f"#define LOGO_DYCI_PNG_LEN {len(data)}u",
    "",
    "#endif /* LOGO_DYCI_H */",
]
with open(HDR, "w") as f:
    f.write("\n".join(lines) + "\n")
print("header:", HDR, os.path.getsize(HDR), "bytes,", len(data), "png bytes")
